    create table app_user (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        invite_code varchar(16) unique,
        profile_visibility varchar(20) not null check (profile_visibility in ('PUBLIC','PRIVATE')),
        username varchar(30) not null,
        bio varchar(2000),
        avatar_url varchar(400000),
        display_name varchar(255) not null,
        email varchar(255) not null,
        password_hash varchar(255) not null,
        primary key (id),
        constraint uk_user_email unique (email),
        constraint uk_user_username unique (username)
    );

    create table experience (
        creativity integer,
        date date not null,
        experience_criteria integer,
        favorite boolean not null,
        flavor integer,
        presentation integer,
        rating integer not null,
        texture integer,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone not null,
        user_id bigint not null,
        visibility varchar(20) not null,
        category varchar(40) not null,
        cuisine_type varchar(60) not null,
        notes varchar(4000),
        photo_url varchar(2000000),
        city varchar(255) not null,
        country varchar(255),
        dish_name varchar(255) not null,
        restaurant_id varchar(255),
        restaurant_name varchar(255) not null,
        primary key (id)
    );

    create table experience_comment (
        created_at timestamp(6) with time zone not null,
        experience_id bigint not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        text varchar(500) not null,
        primary key (id)
    );

    create table experience_like (
        created_at timestamp(6) with time zone not null,
        experience_id bigint not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        primary key (id),
        constraint uk_like_experience_user unique (experience_id, user_id)
    );

    create table experience_tag (
        experience_id bigint not null,
        tag varchar(255)
    );

    create table friendship (
        addressee_id bigint not null,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        requester_id bigint not null,
        status varchar(20) not null check (status in ('PENDING','ACCEPTED')),
        primary key (id),
        constraint uk_friendship_pair unique (requester_id, addressee_id)
    );

    create table notification (
        is_read boolean not null,
        actor_id bigint not null,
        created_at timestamp(6) with time zone not null,
        experience_id bigint,
        id bigint generated by default as identity,
        recipient_id bigint not null,
        type varchar(30) not null check (type in ('FRIEND_REQUEST','FRIEND_ACCEPTED','LIKE','COMMENT')),
        snippet varchar(140),
        primary key (id)
    );

    create table push_key (
        created_at timestamp(6) with time zone not null,
        id bigint not null,
        public_key varchar(120) not null,
        private_key varchar(300) not null,
        primary key (id)
    );

    create table push_subscription (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        auth varchar(100) not null,
        p256dh varchar(200) not null,
        endpoint varchar(1000) not null unique,
        primary key (id)
    );

    create table saved_experience (
        created_at timestamp(6) with time zone not null,
        experience_id bigint not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        primary key (id),
        constraint uk_saved_experience_user unique (experience_id, user_id)
    );

    create index idx_notification_recipient 
       on notification (recipient_id, created_at);

    create index idx_push_subscription_user 
       on push_subscription (user_id);

